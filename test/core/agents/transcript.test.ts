import { describe, expect, it } from 'vitest';
import { TranscriptReader } from '../../../src/core/agents/transcript';

/** Transcript lines as Claude Code writes them (only the fields the reader looks at). */
const prompt = (uuid: string, text: string, entrypoint: string, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ type: 'user', uuid, timestamp: `2026-11-26T08:00:0${uuid.length}Z`, entrypoint, turnOrigin: entrypoint.startsWith('sdk') ? 'sdk' : 'human', message: { role: 'user', content: text }, ...extra });
const say = (text: string, stop: string | null = null) => JSON.stringify({ type: 'assistant', timestamp: '2026-11-26T08:01:00Z', message: { content: [{ type: 'text', text }], stop_reason: stop } });
const tool = (name: string, input: Record<string, unknown>, id = 't1') => JSON.stringify({ type: 'assistant', message: { content: [{ type: 'tool_use', id, name, input }], stop_reason: 'tool_use' } });
const result = (id = 't1', isError = false) => JSON.stringify({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: id, is_error: isError, content: 'ok' }] } });
const lines = (...l: string[]) => `${l.join('\n')}\n`;

describe('TranscriptReader', () => {
  it('picks out a prompt typed in Claude Desktop, with what Claude did and answered', () => {
    const turns = new TranscriptReader().read(
      lines(prompt('d1', 'Is line 9 needed?', 'claude-desktop'), tool('Read', { file_path: 'a.kusto' }), result(), say('Yes, for two reasons.'), say('Both matter.', 'end_turn')),
    );
    expect(turns).toEqual([
      { id: 'd1', where: 'desktop', prompt: 'Is line 9 needed?', startedAt: expect.any(String), endedAt: '2026-11-26T08:01:00Z', reply: 'Yes, for two reasons.\n\nBoth matter.', activity: ['Read a.kusto'], done: true },
    ]);
  });

  it("skips the app's own requests and their answers, which the app has already", () => {
    const reader = new TranscriptReader();
    expect(reader.read(lines(prompt('a1', 'Review the pull request', 'sdk-cli'), say('Two findings.', 'end_turn')))).toEqual([]);
    const [turn] = reader.read(lines(prompt('t1', 'And in a terminal?', 'cli'), say('Same.', 'end_turn')));
    expect(turn).toMatchObject({ where: 'terminal', prompt: 'And in a terminal?', reply: 'Same.' });
  });

  it('is not misled by tool results, notes Claude Code adds, commands, or subagents', () => {
    const turns = new TranscriptReader().read(
      lines(
        prompt('d1', 'Check it', 'claude-desktop'),
        result(),
        prompt('m1', 'Caveat: generated by a command', 'claude-desktop', { isMeta: true }),
        JSON.stringify({ type: 'assistant', isSidechain: true, message: { content: [{ type: 'text', text: 'subagent' }] } }),
        say('Checked.', 'end_turn'),
        prompt('c1', '<bash-input>ls</bash-input>', 'claude-desktop'),
        say('(command output)'),
      ),
    );
    expect(turns.map((t) => [t.id, t.reply])).toEqual([['d1', 'Checked.']]);
  });

  it('carries on across reads, and ends a turn when the next prompt comes without an end', () => {
    const reader = new TranscriptReader();
    const [first] = reader.read(lines(prompt('d1', 'One', 'claude-desktop'), say('Working…')));
    expect(first).toMatchObject({ reply: 'Working…', done: false });
    const changed = reader.read(lines(say('Done.', 'end_turn')));
    expect(changed).toEqual([expect.objectContaining({ id: 'd1', reply: 'Working…\n\nDone.', done: true })]);
    const next = reader.read(lines(prompt('d22', 'Two', 'claude-desktop'), say('Hm')));
    expect(next.map((t) => t.id)).toEqual(['d22']);
    const interrupted = reader.read(lines(prompt('a333', 'From the app', 'sdk-cli')));
    expect(interrupted).toEqual([expect.objectContaining({ id: 'd22', done: true })]);
  });

  it('reads the text of a prompt sent with an image, and ignores lines that are not JSON', () => {
    const withImage = JSON.stringify({ type: 'user', uuid: 'i1', entrypoint: 'claude-desktop', turnOrigin: 'human', message: { content: [{ type: 'image' }, { type: 'text', text: 'What is this?' }] } });
    const [turn] = new TranscriptReader().read(lines('not json', withImage));
    expect(turn).toMatchObject({ prompt: 'What is this?', where: 'desktop' });
  });
});
